#!/usr/bin/env python3
"""Aggregate runs.csv into results.md (per point: right first calls, first-turn
context tokens, cost; and where wrong first calls went)."""
import csv
import os
from collections import defaultdict
from statistics import mean

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, "runs.csv"))))


def verb(tool):
    return tool.split("__")[-1].split("_")[0] if tool else ""


def where(r):
    if r["first_correct"] == "y":
        return None
    if not r["first_tool"]:
        return "no tool call"
    if r["tool_search"] == "on" and r["correct_tool"] not in r["toolsearch_returned"].split("|"):
        return "tool search miss"
    srv = lambda t: t.split("__")[1]
    if srv(r["first_tool"]) == srv(r["correct_tool"]):
        return "other tool, same server"
    if verb(r["first_tool"]) == verb(r["correct_tool"]):
        return "same verb, other server"
    return "other verb, other server"


pts = defaultdict(list)
for r in rows:
    pts[(r["model"].replace("claude-", ""), r["set"], r["tool_search"], int(r["n_tools"]) if r["set"] not in ("fixa",) else "68-73")].append(r)

out = ["# E4 results (generated by results.py from runs.csv)", "",
       f"Runs: {len(rows)}; model(s): {', '.join(sorted({r['model'] for r in rows}))}; Claude Code {', '.join(sorted({r['cc_version'] for r in rows}))}; "
       f"dates (UTC): {min(r['date_utc'] for r in rows)} to {max(r['date_utc'] for r in rows)}; total cost ${sum(float(r['total_cost_usd'] or 0) for r in rows):.2f}", "",
       "| model | set | tool search | tools | runs | right first call | per-run spread (R1..R5 x reps) | first-turn context tokens mean (min-max) | reached right tool | mean cost $ |",
       "|---|---|---|---|---|---|---|---|---|---|"]
order = {"clean": 0, "lookalike": 1, "fixa": 2, "fixb": 3}
for k in sorted(pts, key=lambda k: (k[0], order[k[1]], k[2], str(k[3]).zfill(3))):
    rs = pts[k]
    ok = sum(r["first_correct"] == "y" for r in rs)
    reps = defaultdict(int)
    for r in rs:
        reps[r["run_id"].rsplit("-", 1)[1]] += r["first_correct"] == "y"
    ctx = [int(r["first_ctx_tokens"]) for r in rs if r["first_ctx_tokens"]]
    out.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {len(rs)} | {ok}/{len(rs)} | per rep: {', '.join(f'{v}' for _, v in sorted(reps.items()))} | "
               f"{mean(ctx):.0f} ({min(ctx)}-{max(ctx)}) | {sum(r['reached_correct'] == 'y' for r in rs)}/{len(rs)} | "
               f"{mean(float(r['total_cost_usd'] or 0) for r in rs):.4f} |")

out += ["", "## Wrong first calls", "", "| model | set | tool search | tools | run | request | right tool | first tool | where it went |", "|---|---|---|---|---|---|---|---|---|"]
cls = defaultdict(int)
for r in rows:
    w = where(r)
    if w:
        cls[w] += 1
        out.append(f"| {r['model'].replace('claude-', '')} | {r['set']} | {r['tool_search']} | {r['n_tools']} | {r['run_id']} | {r['request_id']} | {r['correct_tool']} | {r['first_tool'] or '-'} | {w} |")
out += ["", "## Where wrong first calls went (all points)", ""] + [f"- {k}: {v}" for k, v in sorted(cls.items(), key=lambda x: -x[1])]

out += ["", "## Per request (right first call / runs, tool search on, haiku)", "", "| request | clean | lookalike |", "|---|---|---|"]
for rid in sorted({r["request_id"] for r in rows}):
    c = [r for r in rows if r["request_id"] == rid and r["tool_search"] == "on" and "haiku" in r["model"]]
    f = lambda s: f"{sum(r['first_correct'] == 'y' for r in c if r['set'] == s)}/{sum(r['set'] == s for r in c)}"
    out.append(f"| {rid} | {f('clean')} | {f('lookalike')} |")
import glob
import json
sel = kw = 0
for f in glob.glob(os.path.join(HERE, "logs", "raw", "*-on-*.jsonl")):
    for line in open(f):
        e = json.loads(line)
        if e.get("type") == "assistant":
            for b in e["message"].get("content", []):
                if b.get("type") == "tool_use" and b["name"] == "ToolSearch":
                    if b["input"].get("query", "").startswith("select:"):
                        sel += 1
                    else:
                        kw += 1
out += ["", "## How ToolSearch was called (tool search on, all runs)", "",
        f"- by exact name from the deferred list (`select:<names>`): {sel}",
        f"- by keywords: {kw}"]


def ctx(model, kind, ts, n):
    v = [int(r["first_ctx_tokens"]) for r in rows if r["model"].endswith(model) and r["set"] == kind
         and r["tool_search"] == ts and r["n_tools"] == str(n) and r["first_ctx_tokens"]]
    return mean(v) if v else None


out += ["", "## First-turn context per added MCP tool (10 -> 100, haiku)", ""]
for kind, ts in (("clean", "on"), ("lookalike", "on"), ("lookalike", "off")):
    a, b = ctx("haiku-5-5", kind, ts, 10), ctx("haiku-5-5", kind, ts, 100)
    if a and b:
        out.append(f"- {kind}, tool search {ts}: {a:.0f} -> {b:.0f} (+{b - a:.0f}, about {(b - a) / 90:.0f} tokens per added tool)")
open(os.path.join(HERE, "results.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
